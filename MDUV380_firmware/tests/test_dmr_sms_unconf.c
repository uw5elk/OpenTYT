static int fails = 0;

static void check(const char *name, const uint8_t (*ref)[13], int refN,
                  const char *text, uint32_t src, uint32_t dst, int group,
                  uint16_t ipid, uint8_t tms, const uint8_t *key, uint8_t keyId)
{
	uint8_t pt[360];
	int ptLen = dmrSmsPduBuildPlaintext(text, (int)strlen(text), src, dst, tms, ipid, pt);
	if (key) { for (int i = 0; i + 16 <= ptLen; i += 16) { aes256_ecb_encrypt(key, pt + i); } }

	static uint8_t q[DMR_DATA_MAX_BURSTS * BURST_STRIDE];
	memset(q, 0xEE, sizeof q);   /* сміття: хвіст stride має бути обнулений білдером */
	int n = dmrSmsPduBuildUnconf(q, DMR_DATA_MAX_BURSTS, pt, ptLen, src, dst, group, key != NULL, keyId);

	int bad = 0;
	if (n != refN) { printf("  FAIL %s: burst-ів %d, еталон %d\n", name, n, refN); fails++; return; }
	for (int i = 0; i < n; i++)
	{
		const uint8_t *b = q + i * BURST_STRIDE;
		if (memcmp(b, ref[i], 13) != 0)
		{
			printf("  FAIL %s: burst %d\n    еталон:", name, i);
			for (int j = 0; j < 13; j++) printf(" %02x", ref[i][j]);
			printf("\n    маємо: ");
			for (int j = 0; j < 13; j++) printf(" %02x", b[j]);
			printf("\n");
			bad++;
		}
		for (int j = 13; j < BURST_STRIDE; j++)
		{
			if (b[j] != 0) { printf("  FAIL %s: burst %d, хвіст stride [%d]=%02x\n", name, i, j, b[j]); bad++; break; }
		}
	}
	if (bad) { fails++; } else { printf("  ok   %s: %d burst-ів байт-у-байт == 438ec23\n", name, n); }
}

/* Контракт полів, які рев'ю назвало явно (на випадок, якщо еталон колись перегенерують). */
static void check_fields(void)
{
	/* заголовок -- burst 6 (після 6 CSBK) */
	const uint8_t *h = REF_CLEAR_PRIV[6] + 1;
	int ok = (REF_CLEAR_PRIV[6][0] == DTB_DATA_HEADER) && ((h[0] & 0x4F) == 0x02) && (h[9] == 0x00);
	for (int i = 7; i < (int)(sizeof REF_CLEAR_PRIV / sizeof REF_CLEAR_PRIV[0]); i++)
	{
		ok = ok && (REF_CLEAR_PRIV[i][0] == DTB_RATE12_DATA);
	}
	if (!ok) { fails++; printf("  FAIL поля еталона: DPF=2, A=0, o9=00, блоки DTB_RATE12_DATA\n"); }
	else     { printf("  ok   еталон: DPF=2, A=0, o9=00, блоки -- DTB_RATE12_DATA (0x70)\n"); }
}

int main(void)
{
	printf("test_dmr_sms_unconf:\n");
	uint8_t key[32]; for (int i = 0; i < 32; i++) key[i] = (uint8_t)i;
	check_fields();
	check("REF_CLEAR_PRIV",  REF_CLEAR_PRIV,  (int)(sizeof REF_CLEAR_PRIV  / 13),
	      "Test 123", 0x26EA3D, 0x26EA1B, 0, 0x1234, 0x94, NULL, 0);
	check("REF_CLEAR_GROUP", REF_CLEAR_GROUP, (int)(sizeof REF_CLEAR_GROUP / 13),
	      "Hello OpenTYT, long message over several blocks!", 0x26EA3D, 0x0001F5, 1, 0xBEEF, 0x9F, NULL, 0);
	check("REF_ENC_PRIV",    REF_ENC_PRIV,    (int)(sizeof REF_ENC_PRIV    / 13),
	      "Encrypted SMS 42", 0x26EA3D, 0x26EA1B, 0, 0x0102, 0x93, key, 3);

	/* Задовге -> -4, як у 438ec23; замала черга -> -5. */
	{
		static uint8_t big[400]; memset(big, 0x41, sizeof big);
		static uint8_t q[DMR_DATA_MAX_BURSTS * BURST_STRIDE];
		int r1 = dmrSmsPduBuildUnconf(q, DMR_DATA_MAX_BURSTS, big, 381, 1, 2, 0, 0, 0);
		int r2 = dmrSmsPduBuildUnconf(q, 7, big, 40, 1, 2, 0, 0, 0);
		if (r1 != -4 || r2 != -5) { fails++; printf("  FAIL коди помилок: %d %d (очік. -4 -5)\n", r1, r2); }
		else { printf("  ok   коди помилок -4 (задовге) / -5 (не влізло)\n"); }
	}

	printf(fails ? "ПРОВАЛ (%d)\n" : "ПРОЙДЕНО\n", fails);
	return fails ? 1 : 0;
}
