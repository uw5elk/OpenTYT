const uint8_t *aprsIconFind(char table, char code, bool *overlay)
{
	int tab;
	bool ov = false;
	uint8_t no;

	*overlay = false;
	if ((code < '!') || (code > '~'))
	{
		return NULL;
	}
	if (table == '/')
	{
		tab = 0;
	}
	else if (table == '\\')
	{
		tab = 1;
	}
	else if (((table >= '0') && (table <= '9')) || ((table >= 'A') && (table <= 'Z')))
	{
		tab = 1;      /* накладка: піктограма додаткового набору, знак таблиці малюють поверх */
		ov = true;
	}
	else
	{
		return NULL;   /* таблиці, якої в APRS нема */
	}
	no = iconNo[tab][code - '!'];
	if (no == ICON_NONE)
	{
		return NULL;   /* код зарезервований у специфікації або нестандартний -- рамка зі знаком */
	}
	if (no < ICON_COUNT_A)
	{
		*overlay = ov;
		return iconPoolA[no];
	}
#if ! defined(ENABLE_APRS_RX_PROBE)
	*overlay = ov;
	return iconPoolB[no - ICON_COUNT_A];
#else
	return NULL;   /* діагностична збірка: пулу B нема (місце до адреси кодека) -- рамка зі знаком */
#endif
}

