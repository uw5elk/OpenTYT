#define ICON_COUNT  (sizeof(icons) / sizeof(icons[0]))

/* Додаткова таблиця: коди, що малюються піктограмою первинної (транспорт, шлюз, погода -- з накладкою). */
static const struct { char alt; char prim; } alias[] =
{
	{ '>', '>' }, { 'k', 'j' }, { 'u', 'k' }, { 'v', 'v' }, { 's', 'Y' }, { '^', '^' }, { '_', '_' }, { '&', '&' }, { 'S', '(' },
};

static const uint8_t *findIn(char table, char code)
{
	for (size_t i = 0; i < ICON_COUNT; i++)
	{
		if ((icons[i].table == table) && (icons[i].code == code))
		{
			return icons[i].bits;
		}
	}
	return NULL;
}

const uint8_t *aprsIconFind(char table, char code, bool *overlay)
{
	const uint8_t *r;
	char t = table;

	*overlay = false;
	if (t == '/')
	{
		return findIn('/', code);
	}
	if (t != '\\')
	{
		if (!(((t >= '0') && (t <= '9')) || ((t >= 'A') && (t <= 'Z'))))
		{
			return NULL;   /* таблиця, якої в APRS нема */
		}
		*overlay = true;   /* накладка: знак таблиці поверх піктограми додаткового набору */
	}
	r = findIn('\\', code);
	if (r == NULL)
	{
		for (size_t i = 0; i < (sizeof(alias) / sizeof(alias[0])); i++)
		{
			if (alias[i].alt == code)
			{
				r = findIn('/', alias[i].prim);
				break;
			}
		}
	}
	if (r == NULL)
	{
		*overlay = false;
	}
	return r;
}

unsigned aprsIconCount(void)
{
	return (unsigned)ICON_COUNT;
}

