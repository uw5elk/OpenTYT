/*
 * R93 (форк): єдина форма напрямку в усій прошивці й у передпоказі CPS. Окремий заголовок/файл (а не aprs_rx_parse.{h,c}), щоб не змінювати препроцесований вигляд інших
 * файлів і щоб aprs_rx_parse.c лишився ідентичним базі. Увесь код -- лише під APRS_RX (functions/aprs_rx_cfg.h): типова збірка не змінюється.
 */
#ifndef APRS_CHEVRON_H_
#define APRS_CHEVRON_H_

#include <stdint.h>

/* R93: єдина форма напрямку в усій прошивці й у передпоказі CPS -- «навігаційний наконечник»: гострий трикутник з виїмкою ззаду (вістря, дві кутові точки основи й виїмка
 * на осі). Центр (cx,cy) -- середина осі, довжина len -- від центру до вістря (повна висота 2*len); основа -- на відстані len ззаду, півширина 0.8*len; виїмка на 0.72*len
 * ззаду (глибина 0.28*len від основи). Азимут як в aprsArrowGeom(): 0 = північ угорі, за годинниковою, береться по модулю 360. Малювати двома залитими трикутниками:
 * (вістря, ліва, виїмка) і (вістря, права, виїмка) -- виїмка лежить на осі, тож вони не перекриваються. Координати округлено до цілих (від нуля), екран -- y вниз.
 * R98-FIX3 Д: (cx,cy) -- центр ОПИСАНОГО кола (вістря й кутові точки на відстані 1.16*len від нього); середина осі -- на 0.16*len попереду (див. aprs_chevron.c). */
typedef struct
{
	int16_t tx, ty;     /* вістря */
	int16_t lx, ly;     /* ліва кутова точка основи (дивлячись у бік вістря) */
	int16_t rx, ry;     /* права кутова точка основи */
	int16_t nx, ny;     /* виїмка */
} aprsChevron_t;
void aprsChevronGeom(aprsChevron_t *c, int16_t cx, int16_t cy, int16_t len, uint16_t bearingDeg);

#endif /* APRS_CHEVRON_H_ */
