/*
 * dmr_sms_fix.h -- програмна корекція вхідних CONFIRMED rate-3/4 PDU (fix7, 2026-10-05).
 *
 * НАВІЩО. Серія 10 SMS стокова -> форк (нормальна відстань, мала потужність): PDU ок 8,
 * CRC пог 8, два повідомлення не дійшли зовсім (по 3 зіпсовані спроби). Знімки «Діагностика 4»,
 * звірені з ефіром HackRF: трелліс-декодер HR-C6000 псує 1-2 СУСІДНІ трибіти в 1-2 блоках,
 * позиції випадкові. CRC32 PDU (dmrSmsPduCrc32: init 0, без фінального XOR) -- лінійний,
 * тож вектор помилки шукаємо через синдром, без перерахунку всього PDU.
 *
 * МОДЕЛЬ ПОМИЛКИ. Сирий блок rate-3/4 -- 18 Б = 144 біти = 48 трибітів (трибіт t -- біти
 * 3t..3t+2, старший біт першого байта -- біт 0). Кандидат -- один трибіт (7 значень) або два
 * сусідні ненульові трибіти (7x7) в ОДНОМУ блоці. Біти 0..15 -- службові DBSN+CRC9, у PDU їх
 * немає: кандидати, що зачіпають лише їх, пропускаються, а трибіт 5 (біт 15 службовий)
 * береться лише зі значеннями без цього біта -- щоб одна й та сама зміна PDU не рахувалась
 * двічі (інакше хибна «неоднозначність»).
 *
 * ДВА БЛОКИ. Якщо PDU відкритий (не ENC) і контрольна сума заголовка IPv4 (перші 20 Б =
 * блок 0 + 4 Б блока 1) невалідна, помилка точно є в заголовку: спершу шукаємо кандидатів
 * у заголовку, що лагодять суму IPv4 («якорі», до DMR_SMS_FIX_ANCH_MAX), і для кожного --
 * або CRC32 уже сходиться, або другу помилку в ІНШОМУ блоці. Так виправляється знімок #12
 * (блок 0 + блок 2). Дві помилки поза заголовком IPv4 або в шифрованому PDU -- «нема».
 *
 * ПРИЙНЯТТЯ. Кандидат приймається, лише якщо CRC32 зійшовся І verify() (IPv4 header checksum,
 * UDP checksum, якщо ненульовий; для ENC -- після розшифровки) каже «так». Виправлення
 * застосовується, лише якщо такий кандидат РІВНО ОДИН; два й більше -- «неоднозначно», PDU
 * не змінюється.
 *
 * Лише під ENABLE_DMR_DATA + ENABLE_AES; без заліза (хостові тести лінкують цей файл).
 */
#ifndef _OPENGD77_DMR_SMS_FIX_H_
#define _OPENGD77_DMR_SMS_FIX_H_

#include <stdint.h>

#if defined(ENABLE_DMR_DATA) && defined(ENABLE_AES)

#define DMR_SMS_FIX_NONE   0   /* не знайдено жодного прийнятного кандидата */
#define DMR_SMS_FIX_OK     1   /* рівно один -- PDU виправлено на місці */
#define DMR_SMS_FIX_AMBIG  2   /* два й більше -- PDU не змінено */

#define DMR_SMS_FIX_ANCH_MAX  32  /* якорів у заголовку IPv4, що лагодять його суму (сума IPv4 слабка: у тестах до 17 на PDU; більше -- «нема») */
#define DMR_SMS_FIX_MATCH_MAX 4   /* кандидатів зі збіглим CRC32, що перевіряються verify() */

/* 1 -- PDU з цим виправленням прийнятний (IPv4/UDP тощо). pdu уже виправлений; не змінювати. */
typedef int (*dmrSmsFixVerify_t)(const uint8_t *pdu, int len, void *ctx);

/* Одна знайдена зміна: блок, перший трибіт, ширина 1/2, значення (трибіт t -- старші 3 біти). */
typedef struct
{
	uint8_t  blk;
	uint8_t  tri;
	uint8_t  width;
	uint8_t  val;        /* width 1: v; width 2: (v1 << 3) | v2 */
} dmrSmsFixErr_t;

typedef struct
{
	uint8_t        nerr;        /* скільки змін у прийнятому виправленні (1 або 2) */
	dmrSmsFixErr_t err[2];
	uint8_t        anchored;    /* 1 -- працював режим «якір у заголовку IPv4» */
	uint8_t        anchors;     /* скільки якорів знайдено */
	uint8_t        crcMatches;  /* кандидатів зі збіглим CRC32 (до verify) */
	uint8_t        verified;    /* із них прийнятних */
	uint32_t       tested;      /* скільки кандидатів перебрано */
} dmrSmsFixInfo_t;

/* pdu -- зібраний PDU з rate-3/4 блоків (по 16 Б навантаження на блок, останні 4 Б -- CRC32),
 * len кратний 16. plain = 1, якщо PDU -- відкритий IPv4 (дозволяє режим «якір»).
 * verify може бути NULL (тоді лише CRC32 -- тільки для тестів). info може бути NULL. */
int  dmrSmsPduFix34(uint8_t *pdu, int len, int plain, dmrSmsFixVerify_t verify, void *ctx,
                    dmrSmsFixInfo_t *info);

/* Відкритий IPv4/UDP: контрольна сума заголовка IPv4 валідна і UDP checksum валідний (або 0).
 * 1 = так. Перевіряє межі за довжинами з самих заголовків. */
int  dmrSmsPduIpUdpOk(const uint8_t *pkt, int len);

#endif
#endif /* _OPENGD77_DMR_SMS_FIX_H_ */
