/*
 * sms_format.h -- чисті (без заліза й екрана) допоміжні функції показу SMS (ui6):
 * перенесення за словами, форма слова для числа, формат часу з часовим поясом.
 *
 * Спільні для банера (uiNotification.c) і екранів «Повідомлень» (menuMessages.c), тож рядки
 * рахуються однаково всюди. Хост-тест: tests/test_sms_format.c.
 *
 * Лише під ENABLE_AES && ENABLE_DMR_DATA.
 */
#ifndef _OPENGD77_SMS_FORMAT_H_
#define _OPENGD77_SMS_FORMAT_H_

#include <stdint.h>

#if defined(ENABLE_AES) && defined(ENABLE_DMR_DATA)

/* ---- перенесення за словами ------------------------------------------- *
 * Рядок шириною до w символів, що починається з позиції start тексту s (довжина len).
 * Пробіли на початку рядка пропускаються (*lineStart -- перший непробільний символ).
 * Розрив -- на останньому пробілі, що влазить; слово, довше за w, рубається рівно по w.
 * Повертає довжину рядка (без кінцевих пробілів); *next -- звідки шукати наступний рядок
 * (>= len, якщо текст закінчився). Порожній залишок -> 0 і *next = len. Без масивів. */
int smsWrapLine(const char *s, int len, int start, int w, int *lineStart, int *next);
/* Скільки рядків займе текст за smsWrapLine() (порожній текст -> 0). */
int smsWrapCount(const char *s, int len, int w);
/* ui7: рядок і стовпчик позиції pos (0..len) -- курсора або символу, що гортається, -- у тексті,
 * розбитому smsWrapLine() з шириною w. Позиція всередині рядка -- там, де її символ; у пробілах
 * між рядками (вони не малюються) -- одразу за останнім символом рядка, а якщо там уже w-й
 * стовпчик -- початок наступного рядка. Кінець тексту (pos == len) так само: за останнім
 * символом або, якщо рядок повний, -- рядок нижче, стовпчик 0. */
void smsWrapPos(const char *s, int len, int w, int pos, int *row, int *col);

/* ---- форма слова для числа (українська) --------------------------------- *
 * 0: 1, 21, 31 ... (але не 11) -- «непрочитане»; 1: 2-4, 22-24 ... (але не 12-14) --
 * «непрочитані»; 2: решта (0, 5-20, 25-30, 11-14 ...) -- «непрочитаних». */
int smsPluralForm(int n);

/* ---- час ------------------------------------------------------------------ */
/* Менше за це -- годинник не виставлено (2025-01-01 00:00:00 UTC): час не записуємо (0). */
#define SMS_TIME_VALID_MIN  1735689600UL

/* Зсув часового поясу в секундах за nonVolatileSettings.timezone -- рівно як годинник на
 * головному екрані (uiUtilities.c): біт 7 -- «місцевий час», біти 0..6 -- пояс*4 + 64. */
int32_t smsTzOffsetSecs(uint8_t tz);

enum
{
	SMS_TIME_SHORT = 0,   /* «ГГ:ХХ», якщо сьогодні (за місцевим часом), інакше «ДД.ММ» */
	SMS_TIME_FULL,        /* «ДД.ММ ГГ:ХХ» */
	SMS_TIME_HM           /* лише «ГГ:ХХ» */
};
/* t -- секунди UTC (0 = невідомо -> порожній рядок), now -- поточні секунди UTC (для
 * «сьогодні»; < SMS_TIME_VALID_MIN -> «не сьогодні»), tzSecs -- зсув від smsTzOffsetSecs().
 * out -- щонайменше 12 Б. Повертає довжину рядка. */
int smsTimeFormat(uint32_t t, uint32_t now, int32_t tzSecs, int mode, char *out, int outsz);

#endif
#endif /* _OPENGD77_SMS_FORMAT_H_ */
