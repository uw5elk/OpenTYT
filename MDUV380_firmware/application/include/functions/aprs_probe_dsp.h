/*
 * aprs_probe_dsp.h -- чиста (без заліза) обробка відліків для діагностичного екрана
 * «APRS проба» (R2, docs/aprs-rx-feasibility.md, розділ 3).
 *
 * Що рахує на одному джерелі (каналі) звуку:
 *   - середнє (DC), RMS змінної складової і пік відносно середнього -- у сирих одиницях
 *     джерела (I2S: int16; АЦП: 0..4095);
 *   - амплітуду тонів 1200 Гц і 2200 Гц -- Goertzel на блоках по blockLen відліків
 *     (частоти потрапляють рівно в біни: 160 відліків @ 8000 Гц і 192 @ 9600 Гц);
 *   - співвідношення амплітуд у дБ і «хто переважає».
 *
 * Жодного демодулятора AFSK -- лише вимірювання рівня й тонів.
 *
 * Відліки подаються по одному з переривання (I2S DMA або таймер АЦП). Кожні
 * blocksPerWin блоків вікно закривається, apChanPush() повертає true і заповнює
 * результат, а опорний рівень (ref) переходить на щойно виміряне середнє -- так
 * сума квадратів не втрачає точності на великому DC (АЦП ~2048).
 *
 * Пам'ять -- лише сам apChan_t, який кладе викликач (у прошивці -- CCM).
 * Хост-тест: tests/test_aprs_probe_dsp.c.
 */
#ifndef _OPENGD77_APRS_PROBE_DSP_H_
#define _OPENGD77_APRS_PROBE_DSP_H_

#include <stdint.h>
#include <stdbool.h>

#if defined(ENABLE_APRS_RX_PROBE)

/* Підтримані частоти дискретизації: коефіцієнти Goertzel -- константи (без cosf). */
#define AP_FS_I2S   8000U
#define AP_FS_ADC   9600U

/* Співвідношення обмежується цим значенням (дБ) -- і для 0 в знаменнику. */
#define AP_DB_LIMIT 60

enum
{
	AP_WIN_NONE = 0,   /* тони однакові з точністю до 6 дБ */
	AP_WIN_1200,
	AP_WIN_2200,
	AP_WIN_WEAK        /* обидва тони -- шум: сильніший < max(2, RMS/8) (чистий тон дає ~1,4*RMS,
	                    * пакет AFSK -- ~0,2-0,3*RMS кожен, голос на 1000 Гц -- ~0) */
};

typedef struct
{
	/* налаштування */
	float    c1200;       /* 2*cos(2*pi*1200/fs) */
	float    c2200;       /* 2*cos(2*pi*2200/fs) */
	uint16_t blockLen;    /* відліків на блок Goertzel */
	uint16_t blocksPerWin;
	/* поточний блок */
	float    q1a, q2a;    /* стан Goertzel 1200 */
	float    q1b, q2b;    /* стан Goertzel 2200 */
	uint16_t idx;         /* відлік у блоці */
	uint16_t blocks;      /* закритих блоків у вікні */
	/* поточне вікно */
	int32_t  ref;         /* опорний рівень (середнє попереднього вікна) */
	int64_t  sum;         /* сума (x - ref) */
	uint64_t sumSq;       /* сума (x - ref)^2 */
	int32_t  min, max;    /* сирі */
	float    p1200, p2200;/* сума потужностей блоків */
	uint32_t n;           /* відліків у вікні */
} apChan_t;

typedef struct
{
	int32_t  mean;        /* DC, сирі одиниці */
	uint32_t rms;         /* RMS змінної складової */
	uint32_t peak;        /* max |x - mean| */
	uint32_t a1200;       /* амплітуда тону 1200 Гц (як у синусоїди: пік) */
	uint32_t a2200;
	int16_t  ratioDb;     /* 20*lg(a1200/a2200), [-AP_DB_LIMIT..AP_DB_LIMIT] */
	uint8_t  winner;      /* AP_WIN_* */
	uint8_t  valid;       /* 1 -- результат є */
	uint32_t n;           /* відліків у вікні */
} apResult_t;

/* fs -- AP_FS_I2S або AP_FS_ADC (інша -> коефіцієнти 0, тони не міряються).
 * ref -- початковий опорний рівень (I2S: 0; АЦП: 2048). */
void apChanInit(apChan_t *c, uint32_t fs, uint16_t blockLen, uint16_t blocksPerWin, int32_t ref);

/* Один відлік. true -- вікно щойно закрилося, *out заповнено (out може бути NULL). */
bool apChanPush(apChan_t *c, int32_t x, apResult_t *out);

/* ---- R3: розгортка фону ------------------------------------------------------ *
 * Goertzel 100..3900 Гц крок 50 Гц на блоках по 160 відліків (8000 Гц: кожна частота -- рівно
 * на біні, роздільність 50 Гц). За блок -- AP_SWEEP_PER_BLOCK частот, повна розгортка -- 4 блоки,
 * вікно -- AP_SWEEP_ROUNDS розгорток (24 блоки = 480 мс), потужності усереднюються.
 * Результат: топ-1 (частота уточнюється між точками сітки за двома сусідніми бінами, з точністю
 * до кількох Гц -- потрібно режекторному фільтру), топ-2 (не ближче 3 бінів до топ-1), частка
 * топ-1 у загальному RMS (вузька завада -- десятки %, білий шум -- кілька %). */
#define AP_SWEEP_F0         100
#define AP_SWEEP_STEP       50
#define AP_SWEEP_BINS       77
#define AP_SWEEP_N          160
#define AP_SWEEP_PER_BLOCK  20
#define AP_SWEEP_ROUNDS     6
extern const float apSweepCoeff[AP_SWEEP_BINS];   /* 2*cos(2*pi*f/8000) на сітці */

/* 2*cos(2*pi*hz/8000) -- лінійна інтерполяція таблиці (похибка < 0,001, тобто < 0,5 Гц). */
float apCos2(float hz);

typedef struct
{
	float    pw[AP_SWEEP_BINS];  /* сума |X|^2 по блоках вікна */
	float    sumSq;              /* сума квадратів відхилень від середнього блока */
	uint32_t n;                  /* відліків у вікні */
	int32_t  sum;                /* сума відліків вікна (DC) */
	uint8_t  part;               /* наступна група частот */
	uint8_t  rounds;             /* повних розгорток у вікні */
} apBg_t;

typedef struct
{
	float    f1;                 /* Гц, уточнена */
	uint32_t a1;                 /* амплітуда (пік синусоїди), сирі одиниці */
	uint8_t  share1;             /* % від RMS (RMS тону / RMS усього), 0..100 */
	uint16_t f2;                 /* Гц, точка сітки */
	uint32_t a2;
	uint32_t rms;                /* RMS без DC */
	int32_t  mean;               /* DC */
	uint8_t  valid;
} apBgResult_t;

void apBgInit(apBg_t *b);
/* x -- рівно AP_SWEEP_N відліків. true -- вікно закрилося, *out заповнено. */
bool apBgBlock(apBg_t *b, const int16_t *x, apBgResult_t *out);
/* Частота для режекторного фільтра або 0: топ-1 -- вузька (частка >= 50 %), у смузі
 * 900-2500 Гц і не ближче 100 Гц до 1200/2200 (там режекція з'їла б сам тон). */
float apBgNotchHz(const apBgResult_t *r);

/* ---- R4: безперервність потоку (сторінка «потік») -------------------------------- *
 * Сталий тон 1200 Гц через ефір: 1200 * 160 / 8000 = 24 цілі періоди на блок, 12 -- на півблоку.
 * Фаза тону в кожній половині блока (фазор DFT на 80 відліках з опорою на номер відліку в
 * блоці) у безперервному потоці однакова; якщо на межі блоків (DMA-половин) губиться або
 * дублюється k відліків, фаза стрибає на 54 * k градусів. Межу блоків (друга половина
 * попереднього -> перша половина наступного) рахуємо окремо від середини блока (контроль). */
#define AP_STREAM_MIN_AMP   100     /* амплітуда тону, нижче якої блок не аналізується (і >= 0,9 * sigma шуму) */
#define AP_STREAM_JUMP_DEG  30

typedef struct
{
	float    prevRe, prevIm;    /* фазор другої половини попереднього блока */
	uint8_t  havePrev;
	uint32_t blocks;            /* проаналізованих блоків (з тоном) */
	uint32_t jumpsB;            /* стрибків > 30 град на межі блоків */
	uint32_t jumpsIn;           /* ... всередині блока (контроль) */
	uint16_t maxB, maxIn;       /* найбільший стрибок, град */
	uint16_t amp;               /* амплітуда тону в останньому блоці */
	float    sumDphi;           /* сума зсувів фази між половинами блока, рад (для розстройки) */
	uint32_t nDphi;
} apStream_t;

void apStreamInit(apStream_t *st);
/* x -- рівно 160 відліків одного блока (DMA-половини). */
void apStreamBlock(apStream_t *st, const int16_t *x);
/* Розстройка тону від 1200 Гц за середнім зсувом фази між половинами блоків, Гц. */
float apStreamOffsetHz(const apStream_t *st);
/* atan2 у градусах (наближення, похибка < 0,01 град) -- без libm. */
float apAtan2Deg(float y, float x);

/* ---- R5: формат відліку I2S RX у FM-прийомі ---------------------------------- *
 * Запис R4 (А1, FT1D): у 16-бітному півслові каналу звук -- лише біти 0..9, доповнення до двох
 * (знак у біті 9); біти 10..15 однакові між собою, а біт 10 випадковий (P ~ 0,5), не залежить
 * від звуку й є й у тиші -- додає до «сирого» відліку +-1024 (той самий «фон» RMS ~700 у R2/R3).
 * Демодулятор, розгортка, «потік» і Goertzel беруть 10-бітний відлік; USB-запис -- сирий. */
#define AP_FMT_NEAR         480     /* |s| >= цього -- близько до межі +-512 (ризик «перекидання») */

static inline int16_t apSample10(uint16_t u)
{
	return (int16_t)((int32_t)((u & 0x3FFU) ^ 0x200U) - 0x200);
}

typedef struct
{
	uint32_t n;                 /* відліків */
	uint32_t b10;               /* з бітом 10 = 1 */
	uint32_t nonUni;            /* біти 10..15 не однакові (у R4 -- 0) */
	uint32_t nearLim;           /* |s| >= AP_FMT_NEAR (s -- 10-бітний) */
	uint16_t peak;              /* найбільший |s| */
} apFmt_t;

void apFmtInit(apFmt_t *f);
/* n сирих півслів через крок stride (1 -- лише L, 2 -- L,R як у кадрі I2S, береться L):
 * статистика формату в *f (може бути NULL) і відліки для обробки в out: raw16 -- «16 біт як є»
 * (для порівняння), інакше -- 10-бітні apSample10(). */
void apFmtExtract(apFmt_t *f, const uint16_t *u, int stride, int n, bool raw16, int16_t *out);

/* Допоміжні (для тесту теж). */
uint32_t apIsqrt64(uint64_t v);
int16_t  apRatioDb(uint32_t a, uint32_t b);
uint8_t  apWinner(uint32_t a1200, uint32_t a2200);

#endif /* ENABLE_APRS_RX_PROBE */
#endif /* _OPENGD77_APRS_PROBE_DSP_H_ */
