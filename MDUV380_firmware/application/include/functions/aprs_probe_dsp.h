void apStreamBlock(apStream_t *st, const int16_t *x);
/* Розстройка тону від 1200 Гц за середнім зсувом фази між половинами блоків, Гц. */
float apStreamOffsetHz(const apStream_t *st);
/* atan2 у градусах (наближення, похибка < 0,01 град) -- без libm. */
float apAtan2Deg(float y, float x);

/* ---- R5/R7: формат відліку I2S RX у FM-прийомі ---------------------------------- *
 * Модель, виміряна на залізі (docs/aprs-rx-feasibility.md, розділи 9-11): приймач I2S3 (веде
 * HR-C6000) буває зсунутий відносно кордону слова на k бітів. Тоді слово -- це k однакових
 * «сміттєвих» бітів (випадкових, не залежать від звуку навіть у тиші, P ~ 0,5) над старшими
 * (16-k) бітами справжнього відліку S:
 *     слово = (сміття, k копій) << (16-k) | (S >> k),   nbits = 16-k.
 * Бачили: k = 6 («10 біт»: звук у бітах 0..9), k = 5 («11 біт»: біти 0..10) і k = 0 (справжні 16).
 * Формат визначається кожним стартом I2S, а не регістрами кодека.
 * Для демодулятора, розгортки, «потоку» й Goertzel відлік зводиться до масштабу «10 біт»
 * (як k = 6): знакорозширені нижні nbits бітів, зсув праворуч на (nbits-10) (ліворуч, якщо < 10);
 * для nbits = 16 це v >> 6. USB-запис -- завжди сирий. */
#define AP_NBITS_REF        10      /* масштаб, до якого зводяться відліки */
#define AP_NBITS_MIN        8       /* найменший nbits, що розпізнається */
#define AP_NBITS_TRUE16     16      /* «справжні 16 біт» -- піку сміття немає */
#define AP_FMT_NEAR         480     /* |s| >= цього (масштаб 10 біт) -- близько до межі +-512 */

/* Відлік для обробки: знакорозширені нижні nbits (8..16) бітів слова, у масштабі 10 біт.
 * nbits = 0 (формат ще невідомий) -- як 10. */
static inline int16_t apSampleN(uint16_t u, uint8_t nbits)
{
	if (nbits == 0U)
	{
		nbits = AP_NBITS_REF;
	}
	uint32_t sign = 1UL << (nbits - 1U);
	int32_t s = (int32_t)(((uint32_t)u & ((1UL << nbits) - 1UL)) ^ sign) - (int32_t)sign;
	return (int16_t)((nbits >= AP_NBITS_REF) ? (s >> (nbits - AP_NBITS_REF)) : (s * (int32_t)(1UL << (AP_NBITS_REF - nbits))));
}

typedef struct
{
	uint32_t n;                 /* відліків */
	uint32_t nearLim;           /* |s| >= AP_FMT_NEAR (s -- у масштабі 10 біт) */
	uint16_t peak;              /* найбільший |s| */
} apFmt_t;

void apFmtInit(apFmt_t *f);
/* n сирих півслів через крок stride (1 -- лише L, 2 -- L,R як у кадрі I2S, береться L): статистика
 * в *f (може бути NULL) і відліки для обробки в out -- apSampleN(слово, nbits). */
void apFmtExtract(apFmt_t *f, const uint16_t *u, int stride, int n, uint8_t nbits, int16_t *out);

/* ---- R7: детектор nbits ---------------------------------------------------------- *
 * R6 («10» чи «16») на залізі помилявся: слово зі зсувом k = 5 не було ні «10», ні «16», і
 * `v >> 6` брав сміття. Тепер -- за формою розподілу «перемикань біта» по блоку.
 *
 * Лічильник c[j] (j = 1..15) = скільки слів блока мають біт j != біт j-1. Якщо старші біти
 * j..15 -- k однакових копій сміття, то c[i] = 0 для i > j, а c[j] ~ половина слів (сміттєвий біт
 * проти знакового біта j-1 справжнього відліку): різкий ПІК на j = nbits. У справжнього 16-бітного
 * сигналу c[j] = число слів з |v| >= 2^(j-1) -- спадна (функція виживання) і плавна, тож «стрибка
 * вгору при русі до старших бітів» у нього нема.
 *
 * Голос блока (apFmtVote); top -- старший j = 8..15 з c[j] > AP_DET_LO (2 %):
 *   - c[top] >= AP_DET_HI (0,35 блока) і c[top-1] <= AP_DET_MID (0,10) -> голос nbits = top (різкий
 *     пік: усе вище -- нулі; для справжнього сигналу c[top-1] >= c[top], тож це неможливо);
 *   - c[top] >= 0,35, але c[top-1] > 0,10 (гучний пакет у режимі зі сміттям: |s| часто >= 2^(top-2);
 *     або гучний справжній сигнал) -- НЕЙТРАЛЬНО (відхилення від ТЗ R7: «нема чіткого піку -> справжні
 *     16» тут дало б хибні «16» на гучних пакетах);
 *   - AP_DET_SMOOTH (0,30) <= c[top] < 0,35 -- сіра зона, нейтрально (сміття дає ~0,5 +- 0,04, тож
 *     блок із c[top] < 0,35 трапляється раз на ~10^4; справжній гауссів сигнал має c[top] <= ~0,245);
 *   - c[top] < 0,30 -> 16 (справжні 16 біт: вершина профілю мала й плавна);
 *   - усі c[8..15] <= 2 %: 16, якщо c[1..7] > 2 % (тихі справжні 16 біт); цифрова тиша -- нейтрально.
 * Вердикт: AP_DET_STREAK (3) блоки поспіль з однаковим голосом (нейтральні не голосують і серії не
 * переривають; голос за поточний формат серію скидає) -> nbits. Посеред кадру демодулятора формат
 * не міняється до кінця кадру, але не довше AP_DET_HOLD_MAX блоків (3 с). */
#define AP_DET_LO           2       /* % блока: «нуль» */
#define AP_DET_MID          10      /* % блока: «мало» під піком */
#define AP_DET_HI           35      /* % блока: «пік» */
#define AP_DET_SMOOTH       30      /* % блока: нижче -- профіль плавний (справжні 16 біт) */
#define AP_DET_STREAK       3       /* 3 блоки = 60 мс */
#define AP_DET_HOLD_MAX     150     /* 3 с -- найдовший кадр AX.25 (330 байтів) ~2,2 с */

typedef struct
{
	uint8_t  nbits;             /* поточний: 0 -- вердикту ще нема; 8..15 -- сміття над nbits бітами; 16 -- справжні 16 */
	uint8_t  cand;              /* кандидат, що набирає серію */
	uint8_t  streak;            /* голосів поспіль за кандидата */
	uint8_t  lastVote;          /* голос останнього блока (0 -- нейтральний) */
	uint16_t hold;              /* блоків очікування кінця кадру */
	uint32_t switches;          /* зміни вже відомого nbits (початковий вердикт не рахується) */
	uint16_t c[16];             /* лічильники останнього блока: c[j], j = 1..15 (c[0] не використовується) */
} apFmtDet_t;

/* Повне скидання (switches теж). */
void apFmtDetInit(apFmtDet_t *d);
