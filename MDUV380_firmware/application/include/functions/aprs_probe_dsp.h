void apFmtCount(const uint16_t *u, int stride, int n, uint16_t *c);
/* Голос за лічильниками блока з n слів: 0 (нейтрально), 8..15 (сміття над nbits бітами), 16. */
uint8_t apFmtVoteCounts(const uint16_t *c, int n);
/* Голос блока (рахує й c[] у d, якщо d != NULL). */
uint8_t apFmtVote(apFmtDet_t *d, const uint16_t *u, int stride, int n);
/* Блок: голос і, можливо, зміна nbits (inFrame -- демодулятор посеред кадру). true -- nbits
 * щойно став іншим (в т.ч. перший вердикт після рестарту). */
bool apFmtDetBlock(apFmtDet_t *d, const uint16_t *u, int stride, int n, bool inFrame);

/* Допоміжні (для тесту теж). */
uint32_t apIsqrt64(uint64_t v);
